"""Generate this project's client types from the harness's public agent schemas.

The deliberately small renderer rejects unsupported schemas instead of silently
weakening a contract. Run with --check in validation to detect stale types.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from temporal_agent_harness.harness.agent_schema import agent_schema
from agent_dag.live_stage import LiveStageAgentWorkflow
from agent_dag.studio_designer import StudioDesignerAgentWorkflow
from agent_dag.pipeline_agent import FeaturePipelineAgentWorkflow


def identifier(value):
    return value.replace('-', '_')


def render(schema):
    if not schema or schema is True:
        return 'unknown'
    if '$ref' in schema:
        return identifier(schema['$ref'].split('/')[-1])
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(item) for item in schema['enum'])
    for union in ('anyOf', 'oneOf'):
        if union in schema:
            return ' | '.join(render(item) for item in schema[union])
    kind = schema.get('type')
    if kind in ('string', 'boolean', 'null'):
        return kind
    if kind in ('integer', 'number'):
        return 'number'
    if kind == 'array':
        return f'Array<{render(schema["items"])}>'
    if kind == 'object':
        properties = schema.get('properties', {})
        if not properties:
            return f'Record<string, {render(schema.get("additionalProperties", {}))}>'
        required = schema.get('required', [])
        return '{ ' + '; '.join(f'{json.dumps(key)}{"" if key in required else "?"}: {render(value)}'
            for key, value in properties.items()) + ' }'
    raise ValueError(f'Unsupported schema: {schema}')


def generate(cls):
    schema = agent_schema(cls)
    lines = ['// Generated by scripts/generate_agent_types.py. Do not edit.', '']
    for name, definition in schema['$defs'].items():
        lines.append(f'export type {identifier(name)} = {render(definition)};')
    handlers = '; '.join(f'{name}: {{ input: {render(value["input"])}; output: {render(value["output"])} }}'
        for name, value in schema['handlers'].items())
    states = '; '.join(f'{name}: {render(value)}' for name, value in schema['states'].items())
    lines.extend(['', f'export interface {schema["agent"]} {{', f'  handlers: {{ {handlers} }};',
        f'  states: {{ {states} }};', '}', ''])
    return schema['agent'], '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    classes = [LiveStageAgentWorkflow, StudioDesignerAgentWorkflow, FeaturePipelineAgentWorkflow]
    for cls in classes:
        name, text = generate(cls)
        destination = ROOT / 'client_sdk' / (name + '.ts')
        if options.check:
            if not destination.exists() or destination.read_text() != text:
                raise SystemExit(f'Stale agent types: {destination}. Run scripts/generate_agent_types.py.')
        else:
            destination.write_text(text)


if __name__ == '__main__':
    main()
